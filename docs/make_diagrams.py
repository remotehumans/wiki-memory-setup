# ABOUTME: Writes the README's plain-English diagrams as HTML/SVG in docs/: the big picture, the three jobs and what is in your wiki.
# ABOUTME: Usage: python3 docs/make_diagrams.py, then screenshot each page's #diagram element to docs/images/<name>.png.
from html import escape
from pathlib import Path

DOCS = Path(__file__).resolve().parent
SANS = "'Helvetica Neue', Helvetica, Arial, sans-serif"
MONO = "'Courier Prime', monospace"
SERIF = "'Crimson Pro', Georgia, serif"
INK, BODY, MUTED, ACCENT = "#141414", "#4a4a4a", "#6b6b6b", "#E04F18"
SOFT, TINT, RULE = "#f4f4f2", "rgba(224,79,24,0.10)", "rgba(20,20,20,0.16)"


def text(x, y, rows, size=12.5, fill=BODY, dy=17, weight=400, family=SANS, anchor="start"):
    return (f'<text x="{x}" y="{y}" font-family="{family}" font-size="{size}" font-weight="{weight}" fill="{fill}" text-anchor="{anchor}">'
            + "".join(f'<tspan x="{x}" dy="{0 if i == 0 else dy}">{escape(r)}</tspan>' for i, r in enumerate(rows)) + "</text>")


def bullets(items):
    """One bullet per item when a box holds more than one thing; an item's later lines are indented."""
    many = len(items) > 1
    return [("• " if many and j == 0 else "  " if many else "") + line for item in items for j, line in enumerate(item)]


def eyebrow(x, y, label, fill=MUTED):
    return f'<text x="{x}" y="{y}" font-family="{MONO}" font-size="11" letter-spacing="0.16em" fill="{fill}">{escape(label)}</text>'


def box(x, y, w, h, kind="step"):
    style = {"step": ('#ffffff', INK, 1.2), "focal": (TINT, ACCENT, 1.5), "in": (SOFT, RULE, 1), "out": ('#ffffff', "rgba(20,20,20,0.55)", 1)}[kind]
    return f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="6" fill="{style[0]}" stroke="{style[1]}" stroke-width="{style[2]}"/>'


def arrow(x1, y1, x2, y2):
    return f'<line x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}"/>'


def page(name, title, desc, w, h, body):
    html = f'''<!DOCTYPE html>
<!-- ABOUTME: {escape(desc)} -->
<!-- ABOUTME: Generated by docs/make_diagrams.py; exported to docs/images/{name}.png for the README. -->
<html lang="en-GB">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>{escape(title)}</title>
  <link href="https://fonts.googleapis.com/css2?family=Crimson+Pro:ital,wght@0,400;0,500;1,400&family=Courier+Prime:wght@400;700&display=swap" rel="stylesheet">
  <style>
    *, *::before, *::after {{ box-sizing: border-box; margin: 0; padding: 0; }}
    body {{ font-family: {SANS}; background: #ffffff; color: {INK}; }}
    svg {{ width: {w}px; display: block; }}
  </style>
</head>
<body>
  <svg id="diagram" viewBox="0 0 {w} {h}" xmlns="http://www.w3.org/2000/svg" role="img" aria-labelledby="t d">
    <title id="t">{escape(title)}</title>
    <desc id="d">{escape(desc)}</desc>
    <defs><marker id="arrow" markerWidth="8" markerHeight="6" refX="7" refY="3" orient="auto"><polygon points="0 0, 8 3, 0 6" fill="{BODY}"/></marker></defs>
    <rect width="100%" height="100%" fill="#ffffff"/>
    {body}
  </svg>
</body>
</html>
'''
    (DOCS / f"{name}.html").write_text(html)
    return name


def big_picture():
    """Two lanes, you and your AI, with five numbered steps that zigzag between them, so who does what is read first."""
    w, h, label_w, bw, bh, gap = 1340, 600, 120, 200, 160, 40
    lanes = {"you": (72, 210), "ai": (298, 210)}  # top y and height of each lane
    steps = [
        ("you", "Work as usual", ["Chats, meeting notes,", "emails, documents"], "step"),
        ("ai", "Spot it", ["Decisions, people,", "lessons, promises"], "step"),
        ("ai", "File it", ["On the right page,", "linked and sourced"], "focal"),
        ("you", "Ask a question", ["\"What do we know", "about Acme?\""], "step"),
        ("ai", "Answer from it", ["With links to the", "pages it used"], "step"),
    ]
    parts = []
    for key, name, fill in (("you", "You", SOFT), ("ai", "Your AI", "rgba(224,79,24,0.06)")):
        y, lh = lanes[key]
        parts.append(f'<rect x="16" y="{y}" width="{w - 32}" height="{lh}" rx="8" fill="{fill}"/>')
        parts.append(text(36, y + lh // 2 + 9, [name], size=26, fill=ACCENT if key == "ai" else INK, weight=700))
    xs = [label_w + 16 + k * (bw + gap) for k in range(len(steps))]
    ys = {key: y + (lh - bh) // 2 for key, (y, lh) in lanes.items()}
    arrows = []
    for k in range(len(steps) - 1):
        a, b = steps[k][0], steps[k + 1][0]
        x1, x2 = xs[k], xs[k + 1]
        if a == b:
            yy = ys[a] + bh // 2
            arrows.append(f"M{x1 + bw} {yy} H{x2 - 4}")
        else:
            cx, ty = x1 + bw // 2, ys[b] + bh // 2
            start = ys[a] + bh if b == "ai" else ys[a]
            turn = 8 if b == "ai" else -8
            arrows.append(f"M{cx} {start} V{ty - turn} Q{cx} {ty} {cx + 8} {ty} H{x2 - 4}")
    parts.append(f'<g stroke="{BODY}" stroke-width="2" fill="none" marker-end="url(#arrow)">' + "".join(f'<path d="{d}"/>' for d in arrows) + "</g>")
    for k, (lane, title, rows, kind) in enumerate(steps):
        x, y = xs[k], ys[lane]
        parts.append(box(x, y, bw, bh, kind))
        parts.append(f'<circle cx="{x + 34}" cy="{y + 34}" r="16" fill="{ACCENT if kind == "focal" else INK}"/>')
        parts.append(text(x + 34, y + 40, [str(k + 1)], size=17, fill="#ffffff", weight=700, anchor="middle"))
        parts.append(text(x + 20, y + 86, [title], size=21, fill=INK, weight=700))
        parts.append(text(x + 20, y + 116, rows, size=15, fill=BODY, dy=20))
    parts.append(text(16, 40, ["How your memory wiki works"], size=26, fill=INK, family=SERIF))
    parts.append(text(16, h - 30, ["You never sort notes. Your AI files them, and once a week it checks the wiki and tidies it."], size=19, fill=INK, family=SERIF))
    return page("the-big-picture", "Your memory wiki: who does what",
                "Two lanes, you and your AI. You work as usual; your AI spots what matters and files it; you ask a question and your AI answers from the wiki.",
                w, h, "".join(parts))


def three_jobs():
    """The three jobs across the top; under each, what goes in and what comes out."""
    w, x0, bw, gap = 1200, 16, 360, 48
    st_y, st_h, in_y, in_h, out_y, out_h = 64, 92, 196, 88, 324, 128
    jobs = [
        ("Add", "\"Add this to my wiki\", or nothing at all", [["A chat, meeting notes,", "an email or a document"]],
         [["Updated pages for people,", "projects and decisions"], ["Links between them"], ["A saved change you can undo"]]),
        ("Ask", "\"What does my wiki know about X?\"", [["Your question"]],
         [["An answer from your", "own notes"], ["Links to the pages it used"]]),
        ("Check", "\"Check my wiki\", once a week", [["The whole wiki"]],
         [["Duplicates merged"], ["Broken links fixed"], ["Only real questions", "for you"]]),
    ]
    parts, arrows = [], []
    for i in range(len(jobs)):
        cx = x0 + i * (bw + gap) + bw // 2
        arrows += [arrow(cx, st_y + st_h, cx, in_y - 2), arrow(cx, in_y + in_h, cx, out_y - 2)]
    parts.append(f'<g stroke="{BODY}" stroke-width="1.5" fill="none" marker-end="url(#arrow)">' + "".join(arrows) + "</g>")
    for i, (label, say, ins, outs) in enumerate(jobs):
        x, is_focal = x0 + i * (bw + gap), i == 0
        parts += [box(x, st_y, bw, st_h, "focal" if is_focal else "step"), eyebrow(x + 18, st_y + 26, f"JOB {i + 1}", ACCENT if is_focal else MUTED)]
        parts.append(text(x + 18, st_y + 56, [label], size=22, fill=INK, weight=700))
        parts.append(text(x + 18, st_y + 80, [say], size=14, fill=BODY))
        parts += [box(x, in_y, bw, in_h, "in"), eyebrow(x + 18, in_y + 26, "GOES IN"), text(x + 18, in_y + 52, bullets(ins), size=15, dy=20)]
        parts += [box(x, out_y, bw, out_h, "out"), eyebrow(x + 18, out_y + 26, "COMES OUT"), text(x + 18, out_y + 52, bullets(outs), size=15, fill=INK, dy=20)]
    parts.append(text(16, 40, ["Three jobs, and that is all"], size=26, fill=INK, family=SERIF))
    parts.append(text(16, 500, ["Your AI does all three. You talk to it in plain English."], size=20, fill=INK, family=SERIF))
    return page("three-jobs", "The three jobs: add, ask, check",
                "Three jobs your AI does with your wiki: add what matters, answer your questions, and check the wiki once a week.",
                w, 540, "".join(parts))


def inside():
    """A grid of the folders in a new wiki, each with a plain example of what goes there."""
    areas = [
        ("People", "Sam, your accountant"), ("Organisations", "Acme Ltd, a client"), ("Projects", "The new website"),
        ("Offerings", "What you sell, and prices"), ("Events", "The June conference"), ("Places", "The London office"),
        ("Decisions", "We chose Xero, and why"), ("Preferences", "\"Keep emails short\""), ("Observations", "Clients ask about X"),
        ("Questions", "Should we hire?"), ("Ideas", "A podcast, one day"), ("Lessons", "Never send on a Friday"),
        ("Playbooks", "How we onboard a client"), ("Concepts", "Our pricing model"), ("Source material", "The contract, kept as is"),
    ]
    cols, bw, bh, gx, gy, x0, y0 = 5, 224, 88, 16, 16, 16, 64
    parts = []
    for k, (name, example) in enumerate(areas):
        x, y = x0 + (k % cols) * (bw + gx), y0 + (k // cols) * (bh + gy)
        parts.append(box(x, y, bw, bh, "focal" if name == "Decisions" else "step"))
        parts.append(text(x + 16, y + 36, [name], size=18, fill=INK, weight=700))
        parts.append(text(x + 16, y + 62, [example], size=14, fill=BODY))
    w = x0 * 2 + cols * bw + (cols - 1) * gx
    h = y0 + 3 * (bh + gy) + 64
    parts.append(text(16, 40, ["What is in your wiki"], size=26, fill=INK, family=SERIF))
    parts.append(text(16, h - 28, ["One page per thing, in plain text files you own. Open them in any app, like Obsidian."], size=19, fill=INK, family=SERIF))
    return page("whats-inside", "What is in your wiki",
                "Fifteen folders in a new wiki, from people and projects to decisions and lessons, each with an everyday example.",
                w, h, "".join(parts))


if __name__ == "__main__":
    print(", ".join([big_picture(), three_jobs(), inside()]))
